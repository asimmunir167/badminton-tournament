export function tehsilsForDistrictCode(code: string, districtName?: string): string[] {
  const list = TEHSILS_BY_CODE[code];
  if (list?.length) return list;
  const name = districtName ?? PUNJAB_DISTRICTS.find((d) => d.code === code)?.name ?? 'District';
  return [`${name} Central`, `${name} North`, `${name} South`];
}
